import React, { useState } from 'react';
import { X, Play, Pause, Download, Film, ShieldCheck, Activity, Layers } from 'lucide-react';
import { useApp } from '../../context/AppContext';

export const TakeDetailModal: React.FC = () => {
  const { takes, selectedTakeId, setSelectedTakeId, setActiveSheet } = useApp();
  const [isPlaying, setIsPlaying] = useState(false);
  const [scrubPosition, setScrubPosition] = useState(0.4);

  const take = takes.find((t) => t.id === selectedTakeId) || takes[0];

  if (!take) return null;

  const mb = (take.fileSizeBytes / (1024 * 1024)).toFixed(1);

  const handleExport = () => {
    const textContent = `Intégrav Motion Capture Take Export\nID: ${take.id}\nTitle: ${take.title}\nFormat: ${take.format}\nDuration: ${take.durationSeconds}s @ ${take.fps} FPS\nJoints Tracked: ${take.jointsTracked}\nLocal Enclave Validated: Yes (Zero-Knowledge)\nTimestamp: ${take.timestamp}\nGenerated by Intégrav Mobile Workstation.`;
    const blob = new Blob([textContent], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${take.title.replace(/\s+/g, '_')}.${take.format.toLowerCase()}`;
    a.click();
  };

  return (
    <div className="fixed inset-0 z-50 bg-black/85 backdrop-blur-md flex items-end sm:items-center justify-center p-0 sm:p-4">
      <div className="w-full max-w-md bg-[#160e2a] border border-white/10 rounded-t-[32px] sm:rounded-3xl p-5 space-y-3.5 text-left shadow-2xl relative">
        <div className="w-10 h-1.5 bg-slate-600 rounded-full mx-auto -mt-1 mb-2 sm:hidden" />

        <div className="flex items-center justify-between">
          <div className="flex items-center gap-2">
            <div className="p-1.5 rounded-xl bg-pink-500/20 text-pink-300">
              <Film className="w-4 h-4" />
            </div>
            <div>
              <h3 className="text-sm font-bold text-white tracking-tight">
                {take.title}
              </h3>
              <p className="text-[10px] text-slate-400 font-mono">
                Take #{take.takeNumber} · {take.timestamp}
              </p>
            </div>
          </div>

          <button
            onClick={() => {
              setSelectedTakeId(null);
              setActiveSheet(null);
            }}
            className="p-1 rounded-xl bg-white/5 hover:bg-white/10 text-slate-400 hover:text-white transition"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Media Preview Player */}
        <div className="relative w-full h-48 rounded-2xl overflow-hidden bg-black border border-white/10 group">
          {take.thumbnailUrl ? (
            <img
              src={take.thumbnailUrl}
              alt={take.title}
              className="w-full h-full object-cover"
              referrerPolicy="no-referrer"
            />
          ) : (
            <div className="w-full h-full flex items-center justify-center bg-gradient-to-br from-purple-900/40 to-black text-purple-300">
              <Activity className="w-12 h-12 stroke-[1.2]" />
            </div>
          )}

          <div className="absolute inset-0 bg-gradient-to-t from-black/80 via-transparent to-black/30" />

          {/* Center Play button */}
          <button
            type="button"
            onClick={() => setIsPlaying(!isPlaying)}
            className="absolute top-1/2 left-1/2 -translate-x-1/2 -translate-y-1/2 w-12 h-12 rounded-full bg-purple-600/80 hover:bg-purple-500 text-white flex items-center justify-center shadow-lg backdrop-blur-sm transition cursor-pointer"
          >
            {isPlaying ? <Pause className="w-5 h-5" /> : <Play className="w-5 h-5 ml-0.5" />}
          </button>

          {/* Timecode overlay */}
          <div className="absolute bottom-2 left-3 right-3 flex items-center justify-between text-[10px] font-mono text-slate-300">
            <span>{(take.durationSeconds * scrubPosition).toFixed(2)}s</span>
            <span>{take.durationSeconds}s ({Math.floor(take.durationSeconds * take.fps)} frames)</span>
          </div>
        </div>

        {/* Playback scrubber */}
        <div className="space-y-1">
          <input
            type="range"
            min="0"
            max="1"
            step="0.005"
            value={scrubPosition}
            onChange={(e) => setScrubPosition(parseFloat(e.target.value))}
            className="w-full accent-purple-500 h-1.5 bg-black/60 rounded-lg cursor-pointer"
          />
        </div>

        {/* Take Statistics Metrics Grid */}
        <div className="grid grid-cols-3 gap-2 text-center">
          <div className="p-2 rounded-xl bg-black/40 border border-white/5">
            <span className="text-[10px] text-slate-400 block font-mono">Format</span>
            <span className="text-xs font-bold text-white font-mono">{take.format}</span>
          </div>
          <div className="p-2 rounded-xl bg-black/40 border border-white/5">
            <span className="text-[10px] text-slate-400 block font-mono">Payload</span>
            <span className="text-xs font-bold text-purple-300 font-mono">{mb} MB</span>
          </div>
          <div className="p-2 rounded-xl bg-black/40 border border-white/5">
            <span className="text-[10px] text-slate-400 block font-mono">Joints</span>
            <span className="text-xs font-bold text-emerald-400 font-mono">{take.jointsTracked} pts</span>
          </div>
        </div>

        {/* Actions */}
        <div className="pt-2 border-t border-white/10 flex items-center gap-2">
          <button
            type="button"
            onClick={handleExport}
            className="flex-1 py-2.5 rounded-xl font-semibold text-xs text-white bg-purple-600 hover:bg-purple-500 active:scale-98 transition flex items-center justify-center gap-1.5 shadow-md shadow-purple-900/20 cursor-pointer"
          >
            <Download className="w-4 h-4" />
            <span>Download {take.format} Take</span>
          </button>
        </div>
      </div>
    </div>
  );
};
